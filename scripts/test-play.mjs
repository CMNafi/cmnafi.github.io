import assert from 'node:assert/strict';
import { readFile, writeFile, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import ts from 'typescript';
const source = await readFile(new URL('../src/lib/play/predictions.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { validPrediction, scorePrediction, upsertPrediction } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const p = {kind:'f1',eventId:'race-1',player:'Nafi',picks:['1','2','3'],startsAt:'2030-10-13T20:00:00Z',savedAt:'2030-10-12T20:00:00Z'};
assert(validPrediction(p));
assert.equal(scorePrediction(p,{kind:'f1',eventId:'race-1',picks:['1','2','3']}),58);
assert.equal(scorePrediction(p,{kind:'f1',eventId:'race-1',picks:['2','1','3']}),15);
assert.equal(scorePrediction(p,{kind:'f1',eventId:'another-race',picks:['1','2','3']}),null);
assert(!validPrediction({...p,picks:['1','1','3']}));
assert(!validPrediction({...p,savedAt:p.startsAt}));
assert(!validPrediction({...p,startsAt:'bad-date'}));
const now=Date.parse('2030-10-12T21:00:00Z');
assert.throws(()=>upsertPrediction([],{...p,startsAt:'2030-10-12T20:00:00Z'},now));
assert.equal(upsertPrediction([p],{...p,player:'nafi',picks:['3','2','1']},now).length,1);
assert.equal(upsertPrediction([p],{...p,player:'Friend'},now).length,2);
const cricket={...p,kind:'cricket',eventId:'match-1',picks:['Bengal Tigers']};
assert.equal(scorePrediction(cricket,{kind:'cricket',eventId:'match-1',picks:['Bengal Tigers']}),10);
assert.equal(scorePrediction(cricket,{kind:'cricket',eventId:'match-1',picks:['Super Kings']}),0);
const teams=JSON.parse(await readFile(new URL('../src/data/my-teams.json',import.meta.url),'utf8'));
assert.equal(teams.length,5);
const ids=teams.flatMap(t=>t.fixtures.map(f=>f.id));assert.equal(new Set(ids).size,ids.length);
for(const f of teams.flatMap(t=>t.fixtures)){assert(Number.isFinite(Date.parse(f.startsAt)));assert.equal(new Intl.DateTimeFormat('en-US',{timeZone:'America/New_York',hour:'numeric',minute:'2-digit'}).format(new Date(f.startsAt)),'9:00 PM');}
console.log('Play checks passed: scoring, cutoff locks, revisions, separate players, and Eastern fixture times.');
const fetchSource=await readFile(new URL('../src/lib/play/fetch.ts',import.meta.url),'utf8');
const fetchJs=ts.transpileModule(fetchSource,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const fetchModule=`data:text/javascript;base64,${Buffer.from(fetchJs).toString('base64')}`;
const originalFetch=globalThis.fetch;
const mockUrl=`https://example.invalid/play-test-${Date.now()}`;
const mockFile=path.join(process.cwd(),'.cache','play',createHash('sha256').update(mockUrl).digest('hex')+'.json');
try {
  let calls=0;
  globalThis.fetch=async()=>{calls++;return new Response(JSON.stringify([{id:1}]),{status:200});};
  const fresh=await import(fetchModule+'#fresh');
  assert.equal((await fresh.fetchSnapshot(mockUrl,fresh.isRows,[])).stale,false);
  await fresh.fetchSnapshot(mockUrl,fresh.isRows,[]);assert.equal(calls,1);
  await writeFile(mockFile,JSON.stringify({data:[{id:1}],updatedAt:'2020-01-01T00:00:00Z'}));
  globalThis.fetch=async()=>{throw new Error('Offline test');};
  const offline=await import(fetchModule+'#offline');
  const stale=await offline.fetchSnapshot(mockUrl,offline.isRows,[]);assert(stale.stale);assert(!stale.unavailable);assert.equal(stale.data[0].id,1);
  globalThis.fetch=async()=>new Response(JSON.stringify({unexpected:true}),{status:200});
  const malformed=await import(fetchModule+'#malformed');
  const fallback=await malformed.fetchSnapshot(mockUrl+'-invalid',malformed.isRows,[]);assert(fallback.unavailable);assert.deepEqual(fallback.data,[]);
  console.log('Play feed checks passed: request caching, offline snapshot fallback, and malformed API responses.');
} finally { globalThis.fetch=originalFetch;await unlink(mockFile).catch(()=>{}); }
