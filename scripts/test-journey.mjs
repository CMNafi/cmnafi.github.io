import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const source=await readFile(new URL('../src/data/journey/geography.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {places,distance,greatCircle,projectOrthographic,cumulative,legs}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const home=places[0];
assert.equal(distance(home,home),0);
assert(distance(home,places[1])>60&&distance(home,places[1])<70);
assert(Math.abs(distance(home,places[2])-3193)<5);
assert(Math.abs(distance(home,places[1])-distance(places[1],home))<1e-9);
const center=projectOrthographic(home.lat,home.lon,home.lat,home.lon,200,300,300);
assert(Math.abs(center.x-300)<1e-9&&Math.abs(center.y-300)<1e-9&&center.visible);
assert(!projectOrthographic(-home.lat,home.lon+180,home.lat,home.lon,200,300,300).visible);
const path=greatCircle(places[2],places[3]);assert.equal(path.length,65);
for(const v of path)assert(Math.abs(Math.hypot(...v)-1)<1e-9);
const longitudes=path.map(v=>Math.atan2(v[1],v[0])*180/Math.PI);
assert(longitudes.some(n=>n>175)&&longitudes.some(n=>n<-175),'The route crosses the date line over the Pacific.');
assert.equal(cumulative[3],legs.reduce((a,b)=>a+b,0));
assert(cumulative.every((n,i)=>i===0||n>cumulative[i-1]));
assert.throws(()=>greatCircle({lat:0,lon:0},{lat:0,lon:180}));
const mesh=JSON.parse(await readFile(new URL('../src/data/journey/land.json',import.meta.url),'utf8'));
assert(mesh.length>50&&mesh.every(ring=>ring.length>=4));
console.log('Journey geography checks passed: spherical projection, horizon visibility, great-circle endpoints and date-line crossing, distances, and land geometry.');
